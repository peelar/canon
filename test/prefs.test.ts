import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const CLI = join(import.meta.dir, "..", "src", "cli.ts");
let home: string;
let repo: string;

function sh(cwd: string, ...cmd: string[]) {
  const p = Bun.spawnSync(cmd, { cwd, env: { ...process.env, HOME: home }, stdout: "pipe", stderr: "pipe" });
  if (p.exitCode !== 0) throw new Error(`${cmd.join(" ")}: ${p.stderr}`);
  return p.stdout.toString();
}

function prefs(args: string[], env: Record<string, string> = { PREFS_HUMAN: "1" }) {
  const p = Bun.spawnSync(["bun", CLI, ...args], {
    cwd: repo,
    env: { ...process.env, HOME: home, PREFS_ORG_DIR: "", ...env },
    stdin: "ignore",
    stdout: "pipe",
    stderr: "pipe",
  });
  return { code: p.exitCode, out: p.stdout.toString(), err: p.stderr.toString() };
}

function rule(dir: string, id: string, owner: string, status: string, statement: string, extra = "") {
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, `${id}.md`),
    `+++\nid = "${id}"\nowner = "${owner}"\nstatus = "${status}"\nversion = 1\nenforcement = "prompt"\nprovenance = ["https://example.com/t/1"]\n${extra}+++\n\n${statement}\n\n## Why\n\nBecause.\n`,
  );
}

const personalDir = () => join(home, ".config/prefs/repos/github.com/acme/widget");
const read = (rel: string) => readFileSync(join(repo, rel), "utf8");
const status = () => sh(repo, "git", "status", "--porcelain", "--untracked-files=all");

beforeEach(() => {
  home = mkdtempSync(join(tmpdir(), "prefs-home-"));
  repo = mkdtempSync(join(tmpdir(), "prefs-repo-"));
  sh(repo, "git", "init", "-q", "-b", "main");
  sh(repo, "git", "remote", "add", "origin", "https://github.com/acme/widget.git");
  sh(repo, "git", "config", "user.email", "t@example.com");
  sh(repo, "git", "config", "user.name", "t");
});

function commitAgents(text = "# Widget\n\nHand-written guidance.\n") {
  writeFileSync(join(repo, "AGENTS.md"), text);
  sh(repo, "git", "add", "-A");
  sh(repo, "git", "commit", "-qm", "init");
}

describe("personal rules are never committed", () => {
  test("with a committed AGENTS.md, compile leaves git status clean, then cleans up", () => {
    commitAgents();
    rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
    expect(prefs(["compile"]).code).toBe(0);
    expect(read("AGENTS.override.md")).toContain("Search with rg, not grep.");
    expect(read("CLAUDE.local.md")).toContain("Search with rg, not grep.");
    expect(readFileSync(join(home, ".config/amp/AGENTS.md"), "utf8")).toContain("@~/.config/prefs/amp/**/*.md");
    const amp = readFileSync(join(home, ".config/prefs/amp/github.com/acme/widget.md"), "utf8");
    expect(amp).toContain(`'${repo.slice(1)}/**'`);
    expect(read("AGENTS.md")).toBe("# Widget\n\nHand-written guidance.\n");
    expect(status()).toBe("");

    expect(prefs(["retire", "use-rg", "--reason", "no longer needed"]).code).toBe(0);
    expect(existsSync(join(repo, "AGENTS.override.md"))).toBe(false);
    expect(existsSync(join(repo, "CLAUDE.local.md"))).toBe(false);
    expect(existsSync(join(home, ".config/prefs/amp/github.com/acme/widget.md"))).toBe(false);
    expect(existsSync(join(home, ".config/amp/AGENTS.md"))).toBe(false);
    expect(read(".git/info/exclude")).not.toContain("prefs");
    expect(status()).toBe("");
  });

  test("without AGENTS.md, prefs writes an excluded one and git status stays clean", () => {
    writeFileSync(join(repo, "README.md"), "hi\n");
    sh(repo, "git", "add", "-A");
    sh(repo, "git", "commit", "-qm", "init");
    rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
    expect(prefs(["compile"]).code).toBe(0);
    expect(read("AGENTS.md")).toContain("generated by prefs");
    expect(read("AGENTS.md")).toContain("Search with rg, not grep.");
    expect(status()).toBe("");
  });

  test("a hand-written CLAUDE.local.md is left alone", () => {
    commitAgents();
    writeFileSync(join(repo, "CLAUDE.local.md"), "mine\n");
    rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
    const r = prefs(["compile"]);
    expect(r.code).toBe(0);
    expect(r.err).toContain("CLAUDE.local.md exists and was not generated by prefs");
    expect(read("CLAUDE.local.md")).toBe("mine\n");
  });
});

describe("harness files", () => {
  test("CLAUDE.local.md imports AGENTS.md when there is no CLAUDE.md", () => {
    commitAgents();
    rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
    prefs(["compile"]);
    expect(read("CLAUDE.local.md").split("\n")[0]).toBe("@AGENTS.md");
  });

  test("CLAUDE.local.md has no import when CLAUDE.md exists", () => {
    writeFileSync(join(repo, "CLAUDE.md"), "claude rules\n");
    commitAgents();
    rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
    prefs(["compile"]);
    expect(read("CLAUDE.local.md")).not.toContain("@AGENTS.md");
    expect(read("CLAUDE.local.md")).toContain("Search with rg, not grep.");
  });

  test("AGENTS.override.md carries AGENTS.md, shared rules, and personal rules", () => {
    commitAgents();
    rule(join(repo, ".prefs"), "zod-input", "project", "active", "Validate input with zod.", 'applies_to = ["src/api/**"]\n');
    rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
    rule(personalDir(), "maybe-later", "personal", "candidate", "Candidate rules never compile.");
    expect(prefs(["compile"]).code).toBe(0);
    const agents = read("AGENTS.md");
    expect(agents).toContain("Hand-written guidance.");
    expect(agents).toContain("In `src/api/**`: Validate input with zod.");
    expect(agents).not.toContain("rg, not grep");
    const override = read("AGENTS.override.md");
    expect(override).toContain(agents.trimEnd());
    expect(override.indexOf("Validate input with zod.")).toBeLessThan(override.indexOf("Search with rg, not grep."));
    expect(override).not.toContain("Candidate rules never compile.");
    // Shared output is a normal change to commit; personal output never shows up.
    expect(status()).toBe(" M AGENTS.md\n?? .prefs/zod-input.md\n");
  });
});

describe("compile failures", () => {
  test("active rules that conflict fail the build", () => {
    commitAgents();
    rule(join(repo, ".prefs"), "tabs", "project", "active", "Indent with tabs.");
    rule(personalDir(), "spaces", "personal", "active", "Indent with spaces.", 'conflicts = ["tabs"]\n');
    const r = prefs(["compile"]);
    expect(r.code).toBe(1);
    expect(r.err).toContain('active rules "spaces" (personal) and "tabs" (project) conflict');
    expect(existsSync(join(repo, "AGENTS.override.md"))).toBe(false);
  });

  test("a conflict with a retired rule is fine", () => {
    commitAgents();
    rule(join(repo, ".prefs"), "tabs", "project", "retired", "Indent with tabs.", 'reason = "moved to spaces"\n');
    rule(personalDir(), "spaces", "personal", "active", "Indent with spaces.", 'conflicts = ["tabs"]\n');
    expect(prefs(["compile"]).code).toBe(0);
  });

  test("the same id at two levels fails the build", () => {
    commitAgents();
    rule(join(repo, ".prefs"), "use-rg", "project", "active", "Search with rg.");
    rule(personalDir(), "use-rg", "personal", "candidate", "Search with rg, please.");
    const r = prefs(["compile"]);
    expect(r.code).toBe(1);
    expect(r.err).toContain('rule "use-rg" exists at more than one level');
  });
});

test("compile --check reports stale outputs after AGENTS.md changes under an override", () => {
  commitAgents();
  rule(personalDir(), "use-rg", "personal", "active", "Search with rg, not grep.");
  expect(prefs(["compile", "--check"]).code).toBe(1);
  prefs(["compile"]);
  expect(prefs(["compile", "--check"]).code).toBe(0);
  writeFileSync(join(repo, "AGENTS.md"), "# Widget\n\nNew hand-written line.\n");
  const r = prefs(["compile", "--check", "--json"]);
  expect(r.code).toBe(1);
  expect(JSON.parse(r.out).stale.map((s: { path: string }) => s.path)).toEqual([join(repo, "AGENTS.override.md")]);
  prefs(["compile"]);
  expect(read("AGENTS.override.md")).toContain("New hand-written line.");
  expect(prefs(["compile", "--check"]).code).toBe(0);
});

describe("agents can only propose", () => {
  beforeEach(() => commitAgents());

  test("propose writes a candidate that does not compile", () => {
    const r = prefs(["propose", "--json", "--statement", "Prefer bun test.", "--why", "Faster.", "--provenance", "https://ampcode.com/threads/T-1"]);
    expect(r.code).toBe(0);
    const proposed = JSON.parse(r.out).rule;
    expect(proposed.status).toBe("candidate");
    expect(proposed.owner).toBe("personal");
    expect(readFileSync(proposed.path, "utf8")).toContain('status = "candidate"');
    prefs(["compile"]);
    expect(existsSync(join(repo, "AGENTS.override.md"))).toBe(false);
    expect(JSON.parse(prefs(["list", "--json"]).out).rules).toEqual([]);
  });

  test("propose has no way to set a status or overwrite a rule", () => {
    const base = ["propose", "--json", "--statement", "Prefer bun test.", "--why", "Faster.", "--provenance", "https://x.test/1", "--id", "bun-test"];
    expect(prefs([...base, "--status", "active"]).code).toBe(2);
    expect(existsSync(join(personalDir(), "bun-test.md"))).toBe(false);
    rule(personalDir(), "bun-test", "personal", "active", "Prefer bun test.");
    const r = prefs(base);
    expect(r.code).toBe(2);
    expect(JSON.parse(r.out).error).toContain("already exists");
    expect(readFileSync(join(personalDir(), "bun-test.md"), "utf8")).toContain('status = "active"');
  });

  test("approve refuses to run without a terminal", () => {
    prefs(["propose", "--statement", "Prefer bun test.", "--why", "Faster.", "--provenance", "https://x.test/1", "--id", "bun-test"]);
    const r = prefs(["approve", "bun-test"], {});
    expect(r.code).toBe(2);
    expect(r.err).toContain("is for people");
    expect(readFileSync(join(personalDir(), "bun-test.md"), "utf8")).toContain('status = "candidate"');
  });
});
