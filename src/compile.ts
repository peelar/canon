import { existsSync, readFileSync, writeFileSync, rmSync, mkdirSync, readdirSync, rmdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { type Context, home, isTracked, prefsHome } from "./repo";
import { type Level, type Rule, LEVELS, isCompiled, readDir } from "./records";

export const GENERATED = "generated by prefs";
const BEGIN = "<!-- prefs:begin -->";
const END = "<!-- prefs:end -->";
const EX_BEGIN = "# prefs:begin (personal outputs, never commit)";
const EX_END = "# prefs:end";

export class CompileError extends Error {}

export function loadRules(ctx: Context): Rule[] {
  return LEVELS.flatMap((level) => readDir(ctx.dirs[level], level));
}

/** Same id at two levels, or two compiled rules that declare a conflict, fail the build. */
export function validateRules(rules: Rule[]): void {
  const problems: string[] = [];
  const byId = new Map<string, Rule[]>();
  for (const r of rules) byId.set(r.id, [...(byId.get(r.id) ?? []), r]);
  for (const [id, rs] of byId)
    if (rs.length > 1) problems.push(`rule "${id}" exists at more than one level:\n${rs.map((r) => `    ${r.level}: ${r.path}`).join("\n")}`);
  const live = new Map(rules.filter(isCompiled).map((r) => [r.id, r]));
  const seen = new Set<string>();
  for (const r of live.values())
    for (const other of r.conflicts ?? []) {
      const o = live.get(other);
      const pair = [r.id, other].sort().join(" ");
      if (!o || seen.has(pair)) continue;
      seen.add(pair);
      problems.push(`active rules "${r.id}" (${r.level}) and "${o.id}" (${o.level}) conflict; retire one of them or drop it from conflicts`);
    }
  if (problems.length) throw new CompileError(`prefs compile failed:\n  ${problems.join("\n  ")}`);
}

// ---------- rendering ----------

function renderRule(r: Rule): string {
  const scope = r.applies_to?.length ? `In ${r.applies_to.map((g) => `\`${g}\``).join(", ")}: ` : "";
  const statement = r.statement.replace(/\s*\n\s*/g, " ");
  const tag = `(\`${r.id}\` v${r.version}${r.check ? `, checked by \`${r.check}\`` : ""})`;
  const why = r.rationale.split(/\n\s*\n/)[0]?.replace(/\s*\n\s*/g, " ").trim();
  return `- ${scope}${statement} ${tag}${why ? `\n  Why: ${why}` : ""}`;
}

const TITLES: Record<Level, string> = { org: "Org conventions", project: "Project conventions", personal: "Personal conventions" };

function renderSections(rules: Rule[]): string {
  return LEVELS.filter((l) => rules.some((r) => r.level === l))
    .map((l) => `## ${TITLES[l]}\n\n${rules.filter((r) => r.level === l).map(renderRule).join("\n")}`)
    .join("\n\n");
}

/** Replace, insert, or remove the managed block, keeping everything else byte for byte. */
export function applyBlock(text: string | null, inner: string | null, begin = BEGIN, end = END): string | null {
  const block = inner === null ? null : `${begin}\n${inner.trimEnd()}\n${end}\n`;
  const src = text ?? "";
  const s = src.indexOf(begin);
  const e = s >= 0 ? src.indexOf(end, s) : -1;
  let out: string;
  if (s >= 0 && e >= 0) {
    const after = src.slice(e + end.length).replace(/^\n/, "");
    out = block ? src.slice(0, s) + block + after : (src.slice(0, s).replace(/\n+$/, "\n") + after).replace(/^\n+/, "");
  } else if (!block) return text;
  else out = src.trim() ? `${src.replace(/\n*$/, "\n\n")}${block}` : block;
  return out.trim() ? out : null;
}

export const isOwned = (text: string | null) => !!text && text.split("\n", 5).some((l) => l.includes(GENERATED));

// ---------- planning ----------

export type Kind = "shared" | "personal";
export interface Output {
  path: string;
  /** null deletes the file. */
  content: string | null;
  kind: Kind;
}
export interface Plan {
  outputs: Output[];
  warnings: string[];
  rules: Rule[];
}

const read = (p: string) => (existsSync(p) ? readFileSync(p, "utf8") : null);
const ampDir = () => join(prefsHome(), "amp");
const ampGlobal = () => join(home(), ".config", "amp", "AGENTS.md");
export const ampRepoFile = (ctx: Context) => join(ampDir(), `${ctx.key}.md`);

function listMd(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, encoding: "utf8" })
    .filter((f) => f.endsWith(".md"))
    .map((f) => join(dir, f));
}

function ampGlobs(text: string | null): string[] {
  const fm = text?.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
  return [...fm.matchAll(/^\s*-\s*'([^']+)'/gm)].map((m) => m[1]!);
}

export function plan(ctx: Context, opts: { only?: Kind } = {}): Plan {
  const rules = loadRules(ctx);
  validateRules(rules);
  const live = rules.filter(isCompiled);
  const shared = live.filter((r) => r.level !== "personal");
  const personal = live.filter((r) => r.level === "personal");
  const outputs: Output[] = [];
  const warnings: string[] = [];
  const at = (rel: string) => join(ctx.root, rel);

  // Shared rules: a managed block in AGENTS.md, which is committed like any other file.
  const diskAgents = read(at("AGENTS.md"));
  const agentsOwned = isOwned(diskAgents);
  const userAgents = agentsOwned ? null : diskAgents;
  const agents =
    opts.only === "personal"
      ? userAgents
      : applyBlock(userAgents, shared.length ? `${renderSections(shared)}\n\n<!-- Edit rules in .prefs/ or the org prefs repo, then run \`prefs compile\`. -->` : null);
  if (agents !== userAgents || (agentsOwned && agents !== null)) outputs.push({ path: at("AGENTS.md"), content: agents, kind: "shared" });

  // Personal rules: only files prefs owns, listed in .git/info/exclude.
  const header = `<!-- ${GENERATED} for ${ctx.key}: personal rules, never committed. Do not edit; run \`prefs compile\`. -->`;
  const section = renderSections(personal);
  const hasClaudeMd = existsSync(at("CLAUDE.md")) || existsSync(at(".claude/CLAUDE.md"));
  const want: Record<"AGENTS.md" | "AGENTS.override.md" | "CLAUDE.local.md", string | null> = {
    "AGENTS.md": null,
    "AGENTS.override.md": null,
    "CLAUDE.local.md": null,
  };
  let ampFile = false;
  if (personal.length && agents === null && !hasClaudeMd) {
    // No AGENTS.md or CLAUDE.md: one excluded AGENTS.md serves Amp, Codex, and Claude.
    // (With a CLAUDE.md, an AGENTS.md would hide it from Amp, which reads CLAUDE.md as a fallback.)
    want["AGENTS.md"] = `${header}\n\n${section}\n`;
  } else if (personal.length) {
    // Codex reads AGENTS.override.md instead of AGENTS.md, so it carries both.
    want["AGENTS.override.md"] = `${header}\n\n${agents ? `${agents.trimEnd()}\n\n` : ""}${section}\n`;
    // Claude stops reading AGENTS.md once CLAUDE.local.md exists, so import it back.
    want["CLAUDE.local.md"] = `${agents !== null && !hasClaudeMd ? "@AGENTS.md\n\n" : ""}${header}\n\n${section}\n`;
    ampFile = true;
  }

  const excluded: string[] = [];
  for (const [rel, content] of Object.entries(want)) {
    const path = at(rel);
    const disk = read(path);
    if (rel === "AGENTS.md" && content === null) {
      if (agentsOwned && agents === null) outputs.push({ path, content: null, kind: "personal" });
      continue;
    }
    if (rel === "AGENTS.md" && agents !== null) continue;
    if (disk !== null && !isOwned(disk)) {
      if (content !== null) warnings.push(`${rel} exists and was not generated by prefs; left it alone, so its harness won't see personal rules`);
      continue;
    }
    if (content !== null && isTracked(ctx, rel)) {
      warnings.push(`${rel} is tracked by git; prefs won't write personal rules into a tracked file`);
      continue;
    }
    if (content !== null) excluded.push(`/${rel}`);
    if (content !== disk) outputs.push({ path, content, kind: "personal" });
  }
  const exclude = read(ctx.excludePath);
  const nextExclude = applyBlock(exclude, excluded.length ? excluded.join("\n") : null, EX_BEGIN, EX_END);
  if (nextExclude !== exclude) outputs.push({ path: ctx.excludePath, content: nextExclude ?? "", kind: "personal" });

  // Amp with a committed AGENTS.md (the hacky part): a per-repo file under ~/.config/prefs/amp
  // whose globs match this checkout, mentioned from ~/.config/amp/AGENTS.md.
  const repoFile = ampRepoFile(ctx);
  const diskRepoFile = read(repoFile);
  const glob = `${ctx.root.replace(/^\//, "")}/**`;
  // Other checkouts of the same repo keep their globs; personal rules are the same for all of them.
  const globs = new Set(personal.length ? ampGlobs(diskRepoFile) : []);
  if (personal.length) ampFile ? globs.add(glob) : globs.delete(glob);
  const repoContent = globs.size
    ? `---\nglobs:\n${[...globs].sort().map((g) => `  - '${g}'`).join("\n")}\n---\n\n${header}\n\n${section}\n`
    : null;
  if (repoContent !== diskRepoFile) outputs.push({ path: repoFile, content: repoContent, kind: "personal" });
  const anyAmp = listMd(ampDir()).some((f) => f !== repoFile) || repoContent !== null;
  const global = read(ampGlobal());
  const nextGlobal = applyBlock(
    global,
    anyAmp ? "Personal per-repo rules from prefs (each applies only inside its checkout): @~/.config/prefs/amp/**/*.md" : null,
  );
  if (nextGlobal !== global) outputs.push({ path: ampGlobal(), content: nextGlobal, kind: "personal" });

  return { outputs: outputs.filter((o) => !opts.only || o.kind === opts.only), warnings, rules };
}

export function apply(p: Plan): void {
  for (const o of p.outputs) {
    if (o.content === null) {
      rmSync(o.path, { force: true });
      // Drop empty directories prefs created under ~/.config/prefs/amp.
      for (let d = dirname(o.path); d.startsWith(ampDir() + "/"); d = dirname(d)) {
        if (readdirSync(d).length) break;
        rmdirSync(d);
      }
    } else {
      mkdirSync(dirname(o.path), { recursive: true });
      writeFileSync(o.path, o.content);
    }
  }
}

export const describe = (ctx: Context, o: Output) => {
  const rel = relative(ctx.root, o.path);
  const shown = rel.startsWith("..") ? o.path.replace(home(), "~") : rel;
  return `${o.content === null ? "removed" : "wrote"} ${shown} (${o.kind})`;
};
